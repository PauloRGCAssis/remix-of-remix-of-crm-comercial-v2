function normalize(str: string): string {
  return str.trim().toUpperCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

export function inferEstadoFromCidade(cidade: string): string | null {
  if (!cidade?.trim()) return null;
  const key = normalize(cidade);
  return CIDADE_ESTADO_MAP[key] || null;
}
